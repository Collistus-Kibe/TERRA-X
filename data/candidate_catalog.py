def get_all_candidate_cells(res: int = 6) -> List[Dict[str, Any]]:
    """Annotates candidate sites with resolution 6 H3 cells."""
    catalog = []
    for c in RAW_CANDIDATES:
        item = dict(c)
        item["cell_id"] = H3Grid.lat_lng_to_cell(c["lat"], c["lon"], res=res)
        item["h3_resolution"] = res
        catalog.append(item)
    return catalog

